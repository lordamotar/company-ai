def _norm(s):
    return " ".join(str(s or "").strip().lower().replace("ё", "е").split())


def normalize_category(category, subcategory=None):
    """
    Приводит категорию и подкатегорию к справочнику.
    Возвращает (category, subcategory); подкатегория None, если её не удалось сопоставить.
    """
    c = _norm(category)
    sub_hint = None
    cat = None

    for name in CATEGORIES:
        if _norm(name) == c:
            cat = name
            break
    if cat is None and c in _LEGACY:
        cat, sub_hint = _LEGACY[c]
    if cat is None and c:
        for words, name, sub in _KEYWORDS:
            if any(w in " " + c for w in words):
                cat, sub_hint = name, sub
                break
    if cat is None:
        cat = FALLBACK_CATEGORY

    subs = CATEGORIES[cat]["subs"]
    s = _norm(subcategory)
    for name in subs:
        if _norm(name) == s:
            return cat, name
    if sub_hint in subs:
        return cat, sub_hint
    if len(subs) == 1:
        return cat, subs[0]
    return cat, None


