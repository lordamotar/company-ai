def analyze_sentiment_openrouter(text):
    # Промпт для анализа тональности диалога
    prompt = f"""
    Проанализируй следующий диалог между Менеджером и Клиентом:
    ---
    {text}
    ---
    Дай оценку по следующим пунктам:
    1. Тональность клиента в начале и в конце разговора.
    2. Оценка удовлетворенности клиента (от 1 до 5).
    3. Вежливость и профессионализм менеджера.
    4. Были ли решены проблемы клиента.
    
    Ответь кратко на русском языке.
    """
    
    headers = {
        "Authorization": f"Bearer {api_key}",
        "Content-Type": "application/json",
        "HTTP-Referer": "https://github.com/lordamotar/company-ai", # Опционально для OpenRouter
        "X-Title": "Company AI Call Analyzer" # Опционально для OpenRouter
    }
    
    # Используем модель qwen/qwen-2.5-72b-instruct через OpenRouter для детального анализа тональности (тон войса)
    payload = {
        "model": "qwen/qwen-2.5-72b-instruct", 
        "messages": [
            {"role": "user", "content": prompt}
        ]
    }
    
    try:
        print("Отправка запроса в OpenRouter API (модель qwen/qwen-2.5-72b-instruct)...")
        response = requests.post(OPENROUTER_API_URL, headers=headers, json=payload, timeout=60)
        response.raise_for_status()
        result = response.json()
        
        # Получаем ответ от модели
        choices = result.get("choices", [])
        if choices:
            return choices[0].get("message", {}).get("content", "Нет ответа")
        return "Не удалось прочитать ответ модели."
    except Exception as e:
        return f"Произошла ошибка при запросе к OpenRouter: {str(e)}"

